export function buildUserHelp(groupChatId: number, userId: number): string {
  const extra = reminders();
  return [
    "ℹ️ Как пользоваться ботом записи на футбол",
    "",
    ...personalStatus(groupChatId, userId),
    "",
    ...userCommands(),
    ...(extra.length ? ["", ...extra] : []),
  ].join("\n");
}

