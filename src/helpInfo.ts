/**
 * Инструкция (кнопка «ℹ️ Инструкция», команда /help). Приходит нажавшему в личку:
 *  - участнику — только команды участника и его личный статус;
 *  - админу — все админские команды по разделам, состояние чата и, отдельно,
 *    краткий список команд участника.
 * Админские команды есть только в инструкции админа.
 */

/** Личный статус: что записал этот человек и сколько у него голосов. */
function personalStatus(groupChatId: number, userId: number): string[] {
  const session = getSession(groupChatId);
  const own = session?.players.filter((p) => p.userId === userId) ?? [];
  const signup = !session
    ? "запись сейчас закрыта"
    : own.length === 0
      ? "вы пока никого не записали"
      : `вы записали ${own.length}: ${own.map((p) => p.displayName + (p.isReserve ? " (резерв)" : "")).join(", ")}`;

  const vote = getVoteSession(groupChatId);
  let voting = "сейчас не идёт";
  if (vote) {
    const credits = vote.creditsByVoter[userId] || 0;
    const used = vote.votes.filter((v) => v.voterId === userId).length;
    voting = credits ? `идёт — вы отдали ${used} из ${credits} голосов` : "идёт, но вы не были записаны и голосовать не можете";
  }
  return ["Ваш статус:", `• Запись: ${signup}`, `• Голосование за MVP: ${voting}`];
}

function reminders(): string[] {
  const out: string[] = [];
  if (config.reminderHoursBefore > 0) {
    out.push(`⏰ За ${config.reminderHoursBefore} ч до игры бот напомнит в чате, сколько людей в основе и резерве.`);
  }
  if (config.paymentHoursBefore > 0 || config.paymentHoursAfter > 0) {
    out.push(
      `💰 Оплата: ${config.paymentAmount} ₽ с игрока основы на ${config.paymentDetails}. Бот напомнит и отметит вас` +
        (config.paymentHoursBefore > 0 ? ` каждый час за ${config.paymentHoursBefore} ч до игры` : "") +
        (config.paymentHoursAfter > 0 ? ` и ${config.paymentHoursAfter} ч после` : "") +
        ".",
    );
  }
  return out;
}

