module.exports = {
  name: "Незнакомая команда — подсказка, а не молчание",
  async run(t) {
    await t.say(1, "/старт");
    await t.say(1, "/дележка 1 2"); // в основе пусто — ошибка про 4 игрока, не «незнакомая»
    await t.say(4, "/состав");
    t.ok(!!t.find(/Дележки ещё не было/), "/состав — синоним /составы");
    await t.say(4, "/статс");
    t.ok(!!t.find(/Не знаю команду \/статс\. Возможно, вы имели в виду \/статус\. Все команды — \/help\./), "опечатка — подсказка похожей команды");
    await t.say(4, "/абракадабра");
    t.ok(!!t.find(/Не знаю команду \/абракадабра\. Все команды — \/help\./), "совсем незнакомая — ссылка на /help");
    await t.say(1, "/старт сейчас");
    t.ok(!!t.find(/Команда \/старт написана в неверном формате/), "известная команда с лишним текстом — подсказка про формат");
    const before = t.all().length;
    await t.say(4, "обычное сообщение без слэша");
    t.ok(t.all().length === before, "на обычные сообщения бот не отвечает");
  },
};
