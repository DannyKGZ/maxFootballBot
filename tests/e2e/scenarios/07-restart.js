module.exports = {
  name: "Перезапуск бота не теряет голосование, вопросы и очистку",
  async run(t) {
    await t.say(1, "/старт");
    await t.say(2, "+");
    await t.say(2, "+Валера");
    await t.say(1, "/голосование");
    await t.click(2, t.find(/Голосование за MVP/), "Валера");
    await t.say(2, "+");
    t.ok(!!t.find(/Хотите записать другого/), "перед перезапуском открыт вопрос «Да/Нет»");

    await t.restartBot();
    t.ok(t.log.includes("голосований 1") && t.log.includes("открытых вопросов 1"), "после рестарта восстановлены голосование и вопрос", t.log.split("\n")[0]);

    await t.click(2, t.find(/Голосование за MVP/), "Валера");
    t.ok(t.find(/Голосование за MVP/).text.includes("Валера — 2 голоса · Ruslan ×2"), "голос после рестарта добавился к старым");
    await t.click(2, t.find(/Голосование за MVP/), "Ruslan");
    t.ok(t.toast().includes("закончились"), "лимит голосов учитывает голоса до рестарта");
    await t.click(2, t.find(/Хотите записать другого/), "Да");
    t.ok(!!t.find(/Напишите имя нового игрока/), "вопрос, заданный до рестарта, работает");

    await t.say(1, "/итоги");
    t.ok(!t.find(/Хотите записать другого|Напишите имя/), "очистка удалила сообщения, отправленные до рестарта");
    t.ok(!!t.roster() && !!t.find(/^🏆 MVP матча/), "запись и итог остались");
  },
};
