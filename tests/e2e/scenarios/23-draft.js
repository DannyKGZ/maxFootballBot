module.exports = {
  name: "Дележка: админ назначает капитанов, капитаны выбирают по очереди",
  env: { MAX_PLAYERS: "6" },
  async run(t) {
    const draft = () => t.find(/^⚽/);
    await t.say(1, "/старт");
    await t.say(2, "+"); // Ruslan — капитан 1
    await t.say(3, "+"); // Рома — капитан 2
    await t.say(4, "+Андрей +Борис +Вадим +Гена +Резервист"); // Резервист — 7-й, резерв

    await t.say(4, "/дележка");
    t.ok(!!t.find(/только администраторам/) && !draft(), "не-админ не может начать дележку");
    await t.say(1, "/дележка");
    let m = draft();
    t.ok(m && t.buttons(m).join("|") === "👑 Ruslan|👑 Рома|👑 Андрей|👑 Борис|👑 Вадим|👑 Гена|✖️ Отменить дележку (админ)", "капитанов выбирают из основы (резерв не участвует)", m && t.buttons(m));
    await t.click(2, m, "👑 Ruslan");
    t.ok(t.toast() === "Капитанов назначает админ", "капитанов назначает только админ");
    await t.click(1, m, "👑 Ruslan");
    await t.click(1, draft(), "👑 Рома");
    m = draft();
    t.ok(m.text.includes("⚪ Команда 1, Кэп: Ruslan\n1. Ruslan") && m.text.includes("⚫ Команда 2, Кэп: Рома\n1. Рома") && m.text.includes("Выбирает ⚪ Команда 1 (кэп Ruslan)"), "капитаны назначены: команды столбиком, первой выбирает Команда 1", m.text);
    t.ok(t.buttons(m).join("|") === "Андрей|Борис|Вадим|Гена|✖️ Отменить дележку (админ)", "кнопки — оставшиеся игроки основы");

    await t.click(3, m, "Андрей");
    t.ok(t.toast() === "Сейчас выбирает ⚪ кэп Ruslan", "не в свою очередь — нельзя");
    await t.click(2, draft(), "Андрей"); // 1-й выбор: ⚪
    t.ok(draft().text.includes("Выбирает ⚫ Команда 2 (кэп Рома)"), "очередь перешла ко второй команде");
    await t.click(3, draft(), "Борис"); // 2-й выбор: ⚫
    t.ok(draft().text.includes("Выбирает ⚪ Команда 1"), "по одному: снова первая команда");
    await t.click(1, draft(), "Вадим"); // 3-й выбор: ⚪ — админ выбирает за капитана
    t.ok(draft().text.includes("⚪ Команда 1, Кэп: Ruslan\n1. Ruslan\n2. Андрей\n3. Вадим"), "админ может выбрать за капитана; список столбиком", draft().text);
    await t.click(3, draft(), "Гена"); // 4-й выбор: ⚫
    m = draft();
    t.ok(m.text.startsWith("⚽ Составы готовы!") && m.attachments.length === 0, "все разобраны — составы готовы", m.text);
    t.ok(m.text.includes("⚫ Команда 2, Кэп: Рома\n1. Рома\n2. Борис\n3. Гена") && !m.text.includes("Резервист"), "3 на 3 столбиком, резерв не в командах", m.text);

    await t.say(5, "/составы");
    t.ok(t.find(/^⚽ Составы:/) && t.find(/^⚽ Составы:/).text.includes("⚪ Команда 1, Кэп: Ruslan"), "/составы показывает команды любому");
    await t.say(5, "/статус");
    t.ok(t.find(/^📋 Статус/).text.includes("⚫ Команда 2, Кэп: Рома"), "составы видны в /статус");

    await t.say(1, "/дележка 3 4");
    m = draft();
    t.ok(m.text.includes("⚪ Команда 1, Кэп: Андрей") && m.text.includes("⚫ Команда 2, Кэп: Борис") && m.text.includes("Выбирает ⚪ Команда 1 (кэп Андрей)"), "/дележка 3 4 — капитаны по номерам сразу", m.text);
    await t.say(1, "/дележка сброс");
    t.ok(!!t.find(/Дележка отменена/) && !t.find(/^⚽ Дележка/), "/дележка сброс — отменена, сообщение убрано");
  },
};
