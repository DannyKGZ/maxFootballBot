module.exports = {
  name: "Роли для игрока без своего аккаунта (записывает друг) и по имени",
  async run(t) {
    const L = () => t.lines(t.roster()).join("|");
    await t.say(1, "/старт");
    await t.say(3, "+");
    await t.say(2, "+Витя"); // Витю всегда записывает Ruslan

    await t.say(1, "/манишкаНосец");
    const choice = t.find(/^👕 манишкаНосец — сейчас: никто/);
    t.ok(t.buttons(choice).join("|") === "Рома|Витя (записывает Ruslan)|Отмена", "в выборе и записанные друзьями", t.buttons(choice));
    await t.click(1, choice, "Витя");
    t.ok(L() === "1. Витя — 👕 манишкаНосец|2. Рома", "Витя — манишкаНосец", L());

    await t.say(1, "/легенда Володя");
    t.ok(!!t.find(/^✅ 🏆 Легенда: Володя \(до .*Записывать его будет Админ/), "по имени (нет среди участников) — записывает админ");
    await t.say(1, "/легенда Шестой");
    t.ok(!!t.find(/^✅ 🏆 Легенда: Шестой \(до [^)]*\)\.$/m), "по имени участника чата — его собственный аккаунт");
    await t.say(1, "/легенда Володя");
    t.ok(L() === "1. Володя — Легенда 🏆🏅⚽|2. Витя — 👕 манишкаНосец|3. Рома", "Володя — легенда, 1-й", L());

    // Новая запись: оба сразу; убрать Витю может тот, кто его записывает.
    await t.say(1, "/старт");
    await t.click(1, t.find(/Точно начать новую/), "Да, начать новую");
    t.ok(L() === "1. Володя — Легенда 🏆🏅⚽|2. Витя — 👕 манишкаНосец", "в новой записи оба", L());
    await t.say(2, "-Витя");
    await t.click(2, t.find(/Удалить из списка: Витя\?/), "Да");
    t.ok(L() === "1. Володя — Легенда 🏆🏅⚽", "Витю удалил тот, кто его записывает", L());
    await t.say(4, "+");
    await t.say(2, "+Витя");
    t.ok(L() === "1. Володя — Легенда 🏆🏅⚽|2. Витя — 👕 манишкаНосец|3. Влад", "записали снова — опять 2-й", L());

    // Большой чат: участники постранично по 30, удалённые не показываются.
    t.mock.state.members = [
      { user_id: 1, first_name: "Админ", name: "Админ" },
      ...Array.from({ length: 40 }, (_, i) => ({ user_id: 40_000 + i, first_name: `Игрок${String(i).padStart(2, "0")}`, name: `Игрок${String(i).padStart(2, "0")}` })),
      { user_id: 50_000, first_name: "DELETED", last_name: "USER", name: "DELETED USER" },
      { user_id: 777, first_name: "Бот", is_bot: true },
    ];
    await t.say(1, "/легенда");
    const big = t.find(/^🏆 Легенда — сейчас: Володя/);
    const b1 = t.buttons(big);
    t.ok(b1.length === 30 + 4 && b1.includes("1 / 2") && b1.includes("Дальше ▶️") && !b1.some((b) => b.includes("DELETED") || b === "Бот"), "41 участник → 2 страницы, без удалённых и бота", b1);
    await t.click(1, big, "Дальше ▶️");
    const b2 = t.buttons(big);
    t.ok(b2.includes("◀️ Назад") && b2.includes("2 / 2") && b2.includes("Игрок39"), "листание — вторая страница", b2);
    await t.click(1, big, "Игрок39");
    t.ok(/^✅ 🏆 Легенда: Игрок39/.test(big.text), "выбор со второй страницы", big.text);
  },
};
