module.exports = {
  name: "Роли для игрока без своего аккаунта (записывает друг) и по имени",
  async run(t) {
    const L = () => t.lines(t.roster()).join("|");
    await t.say(1, "/старт");
    await t.say(3, "+");
    await t.say(2, "+Витя"); // Витю всегда записывает Ruslan

    await t.say(1, "/легенда");
    const choice = t.find(/^🏆 Легенда — сейчас: никто/);
    t.ok(t.buttons(choice).join("|") === "Рома|Витя (записывает Ruslan)|Отмена", "в выборе и записанные друзьями", t.buttons(choice));
    await t.click(1, choice, "Витя");
    t.ok(L() === "1. Витя — Легенда 🏆🏅⚽|2. Рома", "Витя — легенда, 1-й", L());

    await t.say(1, "/манишкаНосец Володя");
    t.ok(!!t.find(/^✅ 👕 манишкаНосец: Володя\. Записывать его будет Админ/), "по имени — нового игрока записывает админ");
    t.ok(L() === "1. Витя — Легенда 🏆🏅⚽|2. Володя — 👕 манишкаНосец|3. Рома", "Володя сразу 2-й", L());

    // Новая запись: оба сразу; убрать Витю может тот, кто его записывает.
    await t.say(1, "/старт");
    await t.click(1, t.find(/Точно начать новую/), "Да, начать новую");
    t.ok(L() === "1. Витя — Легенда 🏆🏅⚽|2. Володя — 👕 манишкаНосец", "в новой записи оба", L());
    await t.say(2, "-Витя");
    await t.click(2, t.find(/Удалить из списка: Витя\?/), "Да");
    t.ok(L() === "1. Володя — 👕 манишкаНосец", "Витю удалил тот, кто его записывает", L());
    await t.say(2, "+Витя");
    t.ok(L() === "1. Витя — Легенда 🏆🏅⚽|2. Володя — 👕 манишкаНосец", "записали снова — опять 1-й", L());
    await t.say(4, "+");
    t.ok(L() === "1. Витя — Легенда 🏆🏅⚽|2. Володя — 👕 манишкаНосец|3. Влад", "остальные — после ролей", L());
  },
};
