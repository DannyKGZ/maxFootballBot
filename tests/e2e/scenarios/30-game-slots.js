const { dmOf } = require("../harness");

module.exports = {
  name: "/игры: у каждой игры свой день публикации и своё время",
  env: { CHAT_IDS: "-1,-2" },
  async run(t) {
    await t.say(2, "/игры Пн 12:00 Ср 21:20, Чт 12:00 Вс 20:20");
    t.ok(!!t.find(/только администраторам/), "не-админ не меняет игры");

    await t.say(1, "/игры пн 12:00 → среда 21:20, четверг 12.00 - вс 20:20");
    const ok = t.find(/^✅ Игры чата/);
    t.ok(ok && ok.text.includes("Пн 12:00 → игра Ср 21:20; Чт 12:00 → игра Вс 20:20"), "пары разобраны (полные названия дней, «→», «-», 12.00)", ok && ok.text);
    t.ok(ok && /Ближайшая запись откроется (Пн .* на игру Ср .* 21:20|Чт .* на игру Вс .* 20:20)/.test(ok.text), "ближайшая публикация и игра посчитаны по паре", ok && ok.text);
    t.ok(/чат -1: запись по расписанию "0 0 12 \* \* 1", "0 0 12 \* \* 4"/.test(t.log), "по задаче публикации на каждую пару", t.log.split("\n").filter((l) => l.includes("scheduler")));
    t.ok(/чат -2: запись по расписанию "0 0 1 1 \*"/.test(t.log) && !/чат -2: запись по расписанию "0 0 12/.test(t.log), "второй чат не тронут");

    await t.say(1, "/старт");
    const r = t.roster();
    t.ok(r && (/^Футбол в Среда .*\nВ 21:20/.test(r.text) || /^Футбол в Воскресенье .*\nВ 20:20/.test(r.text)), "запись — на ближайшую игру со своим временем", r && r.text.split("\n").slice(0, 2));

    await t.say(3, "/статус");
    t.ok(/Расписание: Пн 12:00 → игра Ср 21:20; Чт 12:00 → игра Вс 20:20 \(настроено через \/игры\)/.test(t.find(/^📋 Статус|Расписание:/).text), "/статус показывает игры");

    await t.say(1, "/игры Пн 25:00 Ср 21:20");
    t.ok(!!t.find(/Не понял время/), "ошибка во времени — подсказка");
    await t.say(1, "/игры");
    t.ok(/Сейчас: Пн 12:00 → игра Ср 21:20/.test(t.all().pop().text), "/игры без текста — показать текущие");

    await t.restartBot();
    t.ok(/чат -1: запись по расписанию "0 0 12 \* \* 1", "0 0 12 \* \* 4"/.test(t.log), "после перезапуска игры сохранились");

    await t.say(1, "/игры сброс", { dm: true });
    t.ok(/♻️ Игры по \/игры отключены/.test(t.all(dmOf(1)).pop().text) && /чат -1: запись по расписанию "0 0 1 1 \*"/.test(t.log), "/игры сброс из лички — обычное расписание");
  },
};
