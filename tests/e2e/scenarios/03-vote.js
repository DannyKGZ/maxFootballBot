module.exports = {
  name: "Голосование, итоги, рейтинг MVP, объединение имён",
  async run(t) {
    await t.say(1, "/старт");
    await t.say(2, "+");
    await t.say(4, "+Сергей +Владимир +Андрей");
    await t.say(1, "/голосование");
    let v = t.find(/Голосование за MVP/);
    t.ok(!!v, "админ запустил голосование");
    t.ok(t.buttons(v).join("|") === "Ruslan|Сергей|Владимир|Андрей|📊 Посмотреть итоги", "кандидаты = записанные, админ-кнопок нет", t.buttons(v));
    await t.click(9, v, "Сергей");
    t.ok(t.toast().includes("только тот, кто был записан"), "незаписанный голосовать не может");
    await t.click(2, t.find(/Голосование за MVP/), "Сергей");
    v = t.find(/Голосование за MVP/);
    t.ok(v.text.includes("Отдано голосов: 1 из 4") && v.text.includes("Сергей ▰▰▰▱▱▱▱▱▱▱ 1") && t.buttons(v)[1] === "Сергей · 1", "голос виден прогресс-баром (шкала — 4 голоса основы) и на кнопке", v.text);
    await t.click(2, v, "Сергей");
    t.ok(t.toast().includes("закончились"), "второй голос при одной записи отклонён");
    for (let i = 0; i < 3; i++) await t.click(4, t.find(/Голосование за MVP/), "Андрей");
    t.ok(t.find(/Голосование за MVP/).text.includes("Андрей ▰▰▰▰▰▰▰▰▱▱ 3"), "у Влада 3 записи — 3 голоса", t.find(/Голосование за MVP/).text);
    await t.click(9, t.find(/Голосование за MVP/), "📊 Посмотреть итоги");
    const live = t.find(/^📊 Итоги голосования/);
    t.ok(live && live.text.includes("1. Андрей\n▰▰▰▰▰▰▰▰▱▱ 3 голоса · Влад ×3") && live.text.includes("Ruslan\n▱▱▱▱▱▱▱▱▱▱ 0 голосов"), "«Посмотреть итоги» — все кандидаты, бары, кто голосовал (видно и незаписанному)", live && live.text);
    await t.click(2, t.find(/Голосование за MVP/), "📊 Посмотреть итоги");
    t.ok(t.count(/^📊 Итоги голосования/) === 1, "повторное нажатие заменяет прошлые итоги");
    await t.click(4, t.find(/Голосование за MVP/), "Сергей");
    t.ok(t.toast().includes("закончились"), "четвёртый голос Влада отклонён");

    await t.say(9, "/итоги");
    t.ok(!t.find(/^🏆 MVP матча/), "не-админ не может /итоги");
    await t.say(1, "/итоги");
    const res = t.find(/^🏆 MVP матча/);
    t.ok(res && res.text.includes("Победитель: Андрей — 3 голоса"), "итог: Андрей — 3 голоса", res && res.text);
    t.ok(!t.find(/Голосование за MVP/), "сообщение голосования удалено");
    t.ok(!!t.roster(), "запись осталась");
    t.ok(t.mvpCount("Андрей") === 1, "Андрею +1 в рейтинге (база)");

    await Promise.all([2, 3, 4, 5, 6].map((u) => t.post(t.messageUpdate(u, "/mvp"))));
    await t.idle();
    t.ok(t.count(/^🏆 Рейтинг MVP/) === 1, "5 одновременных /mvp → одно сообщение");
    await t.click(3, t.roster(), "🏆 Рейтинг MVP");
    t.ok(t.count(/^🏆 Рейтинг MVP/) === 1, "кнопка «Рейтинг MVP» заменяет старое сообщение");

    await t.say(4, "/объединить Андрей = Андрюха");
    t.ok(!!t.find(/только администраторам/) && t.mvpCount("Андрей") === 1, "не-админ не может объединять");
    await t.say(1, "/объединить Андрей = Андрюха");
    t.ok(!!t.find(/«Андрей» объединён с «Андрюха»/), "админ объединил имена");
    await t.say(1, "/объединить Никто = Андрюха");
    t.ok(!!t.find(/нет игрока «Никто»/), "объединение несуществующего — понятная ошибка");

    // Новая победа «Андрей» должна пойти к «Андрюха».
    await t.say(1, "/голосование");
    await t.click(4, t.find(/Голосование за MVP/), "Андрей");
    await t.say(1, "/итоги");
    t.ok(t.mvpCount("Андрюха") === 2 && t.mvpCount("Андрей") === 0, "после объединения победа «Андрей» засчитана «Андрюха»", t.query("SELECT * FROM mvp_players"));
    await t.say(2, "/mvp");
    t.ok(t.find(/^🏆 Рейтинг MVP/).text.includes("Андрюха — 2"), "рейтинг показывает объединённого игрока");
  },
};
